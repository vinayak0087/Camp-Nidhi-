@Composable
fun KpiMetricCard(
    title: String,
    value: String,
    subtitle: String,
    icon: ImageVector,
    accentColor: Color,
    modifier: Modifier = Modifier,
    onClick: (() -> Unit)? = null
) {
    val cardColors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
    val content: @Composable () -> Unit = {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .padding(14.dp),
            verticalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = title,
                    style = MaterialTheme.typography.labelMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis,
                    modifier = Modifier.weight(1f)
                )
                Box(
                    modifier = Modifier
                        .size(30.dp)
                        .clip(RoundedCornerShape(8.dp))
                        .background(accentColor.copy(alpha = 0.14f)),
                    contentAlignment = Alignment.Center
                ) {
                    Icon(
                        imageVector = icon,
                        contentDescription = title,
                        tint = accentColor,
                        modifier = Modifier.size(17.dp)
                    )
                }
            }
            Text(
                text = value,
                style = MaterialTheme.typography.titleLarge.copy(
                    fontFamily = MonoFontFamily,
                    fontWeight = FontWeight.Bold
                ),
                color = MaterialTheme.colorScheme.onSurface,
                maxLines = 1,
                overflow = TextOverflow.Ellipsis
            )
            Text(
                text = subtitle,
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                maxLines = 1,
                overflow = TextOverflow.Ellipsis
            )
        }
    }

    if (onClick != null) {
        Card(
            onClick = onClick,
            colors = cardColors,
            elevation = CardDefaults.cardElevation(defaultElevation = 1.5.dp),
            modifier = modifier
        ) { content() }
    } else {
        Card(
            colors = cardColors,
            elevation = CardDefaults.cardElevation(defaultElevation = 1.5.dp),
            modifier = modifier
        ) { content() }
    }
}

@Composable
fun StatusPill(
    text: String,
    containerColor: Color,
    contentColor: Color,
    modifier: Modifier = Modifier
) {
    Surface(
        color = containerColor,
        shape = RoundedCornerShape(999.dp),
        modifier = modifier
    ) {
        Text(
            text = text,
            color = contentColor,
            style = MaterialTheme.typography.labelSmall.copy(fontWeight = FontWeight.SemiBold),
            modifier = Modifier.padding(horizontal = 9.dp, vertical = 4.dp),
            maxLines = 1
        )
    }
}

@Composable
fun ExpenseStatusPill(status: ExpensePaymentStatus, modifier: Modifier = Modifier) {
    val (bg, fg, label) = when (status) {
        ExpensePaymentStatus.PAID -> Triple(StatusPaidContainer, StatusPaidGreen, "Paid")
        ExpensePaymentStatus.PARTIALLY_PAID -> Triple(StatusInfoContainer, StatusInfoBlue, "Partial Paid")
        ExpensePaymentStatus.APPROVED -> Triple(StatusPaidContainer, StatusPaidGreen, "Approved")
        ExpensePaymentStatus.PENDING_APPROVAL -> Triple(StatusPendingContainer, StatusPendingAmber, "Pending")
        ExpensePaymentStatus.SUBMITTED -> Triple(StatusInfoContainer, StatusInfoBlue, "Submitted")
        ExpensePaymentStatus.REJECTED -> Triple(StatusDangerContainer, StatusDangerCrimson, "Rejected")
        ExpensePaymentStatus.DRAFT -> Triple(StatusNeutralContainer, StatusNeutralSlate, "Draft")
    }
    StatusPill(text = label, containerColor = bg, contentColor = fg, modifier = modifier)
}

@Composable
fun IncomeStatusPill(status: IncomePaymentStatus, modifier: Modifier = Modifier) {
    val (bg, fg, label) = when (status) {
